// Standalone disposable browser fixture. Never import the store before isolation.
import {mkdtemp, writeFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const root=await mkdtemp(join(tmpdir(),'orchestra-browser-redesign-'));
process.env.RELAY_DATA_DIR=join(root,'data');
process.env.ORCHESTRA_DATA_DIR=process.env.RELAY_DATA_DIR;
delete process.env.RELAY_TLS_CERT;
delete process.env.RELAY_TLS_KEY;
const store=await import('../src/server/store.js');
const git=await import('../src/server/git.js');
const {createApp}=await import('../src/server/app.js');
const {createServer}=await import('vite');
const owner=store.redeemInvite(store.issueInvite(undefined,'owner').token,'Browser QA');
const project=store.put('projects',{name:'Browser fixture'});
const source=join(root,'source');
await git.command('git',['init','-b','main',source]);
await git.git(source,'config','user.name','Browser QA');
await git.git(source,'config','user.email','browser@example.invalid');
await writeFile(join(source,'hello.ts'),'export const greeting = "before";\nexport const keep = true;\n');
await writeFile(join(source,'notes with spaces.md'),'# Browser smoke\n');
await git.git(source,'add','.');
await git.git(source,'commit','-m','fixture base');
await git.git(source,'checkout','-b','smoke-change');
await writeFile(join(source,'hello.ts'),'export const greeting = "after";\nexport const keep = true;\nexport const added = 42;\n');
await writeFile(join(source,'notes with spaces.md'),'# Browser smoke\n\nSecond file changed.\n');
await git.git(source,'add','.');
await git.git(source,'commit','-m','fixture change');
await git.git(source,'checkout','main');
const repo=await git.importRepository(source,'Smoke repository',project.id,'main');
const change=await git.createChange(repo,'smoke-change','main','Browser smoke change',owner.user.id);
const app=await createApp();
await app.listen({host:'127.0.0.1',port:0});
const address=app.server.address() as {port:number};
const frontend=await createServer({configFile:false,root:process.cwd(),server:{host:'127.0.0.1',port:0,proxy:{'/api':`http://127.0.0.1:${address.port}`}},appType:'spa'});
await frontend.listen();
const port=(frontend.httpServer!.address() as {port:number}).port;
console.log('BROWSER_FIXTURE '+JSON.stringify({url:`http://127.0.0.1:${port}`,token:owner.token,projectId:project.id,repoId:repo.id,changeId:change.id,root}));
let closing=false;
async function close(){if(closing)return;closing=true;await frontend.close();await app.close();store.db.close();await rm(root,{recursive:true,force:true});process.exit(0);}
process.on('SIGTERM',()=>void close());
process.on('SIGINT',()=>void close());
